#!/bin/sh
# DOWNSTREAM PATCH (APT system updates): test the .deb file installer's
# model against generated packages. See ai-patches/TEST.md D1.
# Read-only: PackageKit only reads the files and *simulates* installing
# them; nothing is installed.
#
# Needs: PackageKit running (or D-Bus activatable), dpkg-deb, gcc,
# pkg-config, libglib2.0-dev.
#
# Usage:  ai-patches/patches/harness/deb-check.sh
# Exit 1 when a case does not give the expected result.
set -e

HERE="$(cd "$(dirname "$0")" && pwd)"
REPO="${BZ_REPO:-$(cd "$HERE/../../.." && pwd)}"
SRC="$(cd "${BZ_APT_SRC:-$REPO/src}" && pwd)"
OUT="$REPO/build/apt-tests/deb"
. "$HERE/brand.sh"

rm -rf "$OUT" && mkdir -p "$OUT"
cd "$OUT"

printf '#define GETTEXT_PACKAGE "%s"\n' "$GETTEXT_DOMAIN" > config.h
# shellcheck disable=SC2046
gcc -std=gnu11 -Wall -Wextra -Werror -Wno-unused-parameter \
    -Wdeclaration-after-statement -Wshadow -Wmissing-declarations \
    -I. -I"$SRC" $(pkg-config --cflags gio-unix-2.0) \
    -o deb-check "$SRC/bz-deb-installer.c" "$HERE/deb-check.c" \
    $(pkg-config --libs gio-unix-2.0)

# make_deb NAME VERSION DEPENDS [app]
make_deb () {
  root="$OUT/root-$1-$2"
  mkdir -p "$root/DEBIAN"
  {
    echo "Package: $1"
    echo "Version: $2"
    echo "Architecture: all"
    echo "Maintainer: Test <test@example.invalid>"
    [ -n "$3" ] && echo "Depends: $3"
    echo "Description: Test package for the deb installer"
    echo " Generated by ai-patches/patches/harness/deb-check.sh."
  } > "$root/DEBIAN/control"
  if [ "$4" = app ]; then
    mkdir -p "$root/usr/share/applications" "$root/usr/share/icons/hicolor/scalable/apps"
    printf '[Desktop Entry]\nType=Application\nName=Deb Check App\nName[id]=Aplikasi Uji Deb\nExec=true\nIcon=%s\n' "$1" \
      > "$root/usr/share/applications/$1.desktop"
    cp "$REPO/data/icons/hicolor/scalable/apps/$APP_ID.svg" "$root/usr/share/icons/hicolor/scalable/apps/$1.svg"
  fi
  dpkg-deb --root-owner-group -b "$root" "$OUT/$1_$2_all.deb" >/dev/null
  echo "$OUT/$1_$2_all.deb"
}

FAILED=0
# check FILE "description" KEY=VALUE...
check () {
  file="$1"; desc="$2"; shift 2
  result="$(LANGUAGE=C ./deb-check "$file" 2>/dev/null)" || { echo "FAIL  $desc: deb-check failed"; FAILED=1; return; }
  for want in "$@"; do
    if ! echo "$result" | grep -qxF "$want"; then
      echo "FAIL  $desc: wanted $want, got:"; echo "$result" | sed 's/^/        /'
      FAILED=1; return
    fi
  done
  echo "PASS  $desc"
}

base_version="$(dpkg-query -W -f '${Version}' base-files)"

check "$(make_deb bz-deb-check-app 1.0 "" app)" "new app with launcher and icon" \
  state=ready action=install name=bz-deb-check-app version=1.0 "installed_version=(null)" \
  "app_name=Deb Check App" desktop_id=bz-deb-check-app.desktop icon=from-package removed=0
check "$(make_deb bz-deb-check-blocked 1.0 bz-deb-check-does-not-exist)" "missing dependency blocks the install" \
  state=blocked action=install "error=Other packages it needs are missing, or conflict with the installed system."
check "$(make_deb base-files "$base_version" "")" "same version as installed: nothing to do" \
  state=ready action=none "installed_version=$base_version"
check "$(make_deb base-files 99999 "")" "newer version of an installed package: update" \
  state=ready action=upgrade version=99999 "installed_version=$base_version"
echo "not a package" > "$OUT/broken.deb"
check "$OUT/broken.deb" "damaged file" \
  state=failed "error=The file is damaged, or it is not a software package for this system."
check "$OUT/missing.deb" "missing file" state=failed

exit $FAILED
